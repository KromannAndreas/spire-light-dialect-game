const DISTINCT_DIALECTS = [...new Set(DIALECTS.map((item) => item.dialect))];

function hash(input: string) {
  return [...input].reduce((value, char) => (value * 31 + char.charCodeAt(0)) >>> 0, 2166136261);
}

export function questionFor(code: string, round: number) {
  const clip = DIALECTS[(hash(code) + round * 7) % DIALECTS.length];
  const distractors: string[] = [];
  let cursor = hash(`${code}-${round}`) % DISTINCT_DIALECTS.length;
  while (distractors.length < 3) {
    const candidate = DISTINCT_DIALECTS[cursor % DISTINCT_DIALECTS.length];
    if (candidate !== clip.dialect && !distractors.includes(candidate)) distractors.push(candidate);
    cursor += 5;
  }
  const options = [clip.dialect, ...distractors];
  const shift = hash(`shift-${code}-${round}`) % options.length;
  return { clip, options: [...options.slice(shift), ...options.slice(0, shift)] };
}

